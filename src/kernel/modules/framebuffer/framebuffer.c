static void hsv_to_rgb(uint32_t h, uint8_t *r, uint8_t *g, uint8_t *b) {
    uint32_t region = h / 43;
    uint32_t remainder = (h - region * 43) * 6;
    uint32_t p = (255 * (255 - remainder)) >> 8;
    uint32_t q = (255 * (255 - ((255 - remainder) * (43 - (h % 43))) / 43)) >> 8;
    uint32_t t = 255 - p;
    switch (region) {
        case 0:  *r = 255; *g = (uint8_t)p;   *b = (uint8_t)t;   break;
        case 1:  *r = (uint8_t)q;   *g = 255; *b = (uint8_t)t;   break;
        case 2:  *r = (uint8_t)t;   *g = 255; *b = (uint8_t)p;   break;
        case 3:  *r = (uint8_t)t;   *g = (uint8_t)q;   *b = 255; break;
        case 4:  *r = (uint8_t)p;   *g = (uint8_t)t;   *b = 255; break;
        default: *r = 255; *g = (uint8_t)t;   *b = (uint8_t)q;   break;
    }
}

void fb_init(BootInfo *info) {
    fb         = info->framebuffer;
    screen_w   = info->fb_width;
    screen_h   = info->fb_height;
    fb_pitch_val = info->fb_pitch;
    fb_format  = info->fb_format;
}

uint64_t fb_width(void)  { return screen_w; }
uint64_t fb_height(void) { return screen_h; }
uint64_t fb_pitch(void)  { return fb_pitch_val; }

uint32_t fb_rgb(uint8_t r, uint8_t g, uint8_t b) {
    if (fb_format == FB_FORMAT_BGR)
        return ((uint32_t)r) | ((uint32_t)g << 8) | ((uint32_t)b << 16);
    return ((uint32_t)b) | ((uint32_t)g << 8) | ((uint32_t)r << 16);
}

void fb_put_pixel(uint64_t x, uint64_t y, uint32_t color) {
    if (x >= screen_w || y >= screen_h) return;
    
    void *target = use_double_buffer ? back_buffer : fb;
    
    uint32_t *pixel = (uint32_t *)((uint8_t *)target + y * fb_pitch_val + x * 4);
    *pixel = color;
}

void fb_clear(uint32_t color) {
    if (use_double_buffer && back_buffer) {
        memset(back_buffer, color, screen_h * fb_pitch_val);
    } else {
        for (uint64_t y = 0; y < screen_h; y++)
            for (uint64_t x = 0; x < screen_w; x++)
                fb_put_pixel(x, y, color);
    }
}

void fb_draw_char(char c, uint64_t x, uint64_t y, uint32_t fg, uint32_t bg) {
    if (c < 32 || c > 126) c = '?';
    const uint8_t *glyph = font[c - 32];
    for (int row = 0; row < 8; row++) {
        for (int col = 0; col < 8; col++) {
            uint32_t color = (glyph[row] & (0x01 << col)) ? fg : bg;
            fb_put_pixel(x + (uint64_t)col, y + (uint64_t)row, color);
        }
    }
}

void fb_draw_string(const char *s, uint64_t x, uint64_t y, uint32_t fg, uint32_t bg) {
    while (*s) {
        fb_draw_char(*s++, x, y, fg, bg);
        x += 8;
    }
}

void fb_draw_color_bar(uint64_t y, uint64_t height) {
    if (height == 0) return;
    uint64_t bar_bottom = y + height;
    if (bar_bottom > screen_h) bar_bottom = screen_h;

    uint64_t third = height / 3;
    if (third == 0) third = 1;

    for (uint64_t row = y; row < y + third && row < bar_bottom; row++) {
        for (uint64_t x = 0; x < screen_w; x++) {
            uint8_t r = (uint8_t)((x * 255) / (screen_w ? screen_w : 1));
            uint8_t g = (uint8_t)(255 - r);
            fb_put_pixel(x, row, fb_rgb(r, g, 0));
        }
    }

    uint64_t mid_start = y + third;
    for (uint64_t row = mid_start; row < mid_start + third && row < bar_bottom; row++) {
        for (uint64_t x = 0; x < screen_w; x++) {
            uint8_t g = (uint8_t)((x * 255) / (screen_w ? screen_w : 1));
            uint8_t b = (uint8_t)(255 - g);
            fb_put_pixel(x, row, fb_rgb(0, g, b));
        }
    }

    uint64_t hue_start = mid_start + third;
    for (uint64_t row = hue_start; row < bar_bottom; row++) {
        for (uint64_t x = 0; x < screen_w; x++) {
            uint8_t r, g, b;
            uint32_t hue = (uint32_t)((x * 255) / (screen_w ? screen_w : 1));
            hsv_to_rgb(hue, &r, &g, &b);
            fb_put_pixel(x, row, fb_rgb(r, g, b));
        }
    }
}

void fb_draw_filled_circle(uint64_t x0, uint64_t y0, uint64_t radius) {
    for (int64_t y = -(int64_t)radius; y <= (int64_t)radius; y++) {
        for (int64_t x = -(int64_t)radius; x <= (int64_t)radius; x++) {
            if (x * x + y * y <= (int64_t)radius * (int64_t)radius) {
                uint32_t hue = (uint32_t)(((x + (int64_t)radius) * 255) / (2 * radius));
                uint8_t r, g, b;
                uint32_t region = hue / 43;
                uint32_t remainder = (hue - region * 43) * 6;
                uint32_t p = (255 * (255 - remainder)) >> 8;
                uint32_t q = (255 * (255 - ((255 - remainder) * (43 - (hue % 43))) / 43)) >> 8;
                uint32_t t = 255 - p;
                switch (region) {
                    case 0:  r = 255; g = (uint8_t)p;   b = (uint8_t)t;   break;
                    case 1:  r = (uint8_t)q;   g = 255; b = (uint8_t)t;   break;
                    case 2:  r = (uint8_t)t;   g = 255; b = (uint8_t)p;   break;
                    case 3:  r = (uint8_t)t;   g = (uint8_t)q;   b = 255; break;
                    case 4:  r = (uint8_t)p;   g = (uint8_t)t;   b = 255; break;
                    default: r = 255; g = (uint8_t)t;   b = (uint8_t)q;   break;
                }
                fb_put_pixel(x0 + (uint64_t)x, y0 + (uint64_t)y, fb_rgb(r, g, b));
            }
        }
    }
}

void fb_enable_double_buffering(void) {
    back_buffer = mem_alloc(screen_h * fb_pitch_val);
    if (back_buffer)
        use_double_buffer = 1;
    else
        fb_draw_string("WARN: double buffer alloc failed", 32, 32, FB_COLOR_RED, FB_COLOR_BLACK);
}

void fb_swap_buffers(void) {
    if (use_double_buffer && back_buffer) {
        uint8_t *src = (uint8_t *)back_buffer;
        uint8_t *dst = (uint8_t *)fb;
        for (uint64_t y = 0; y < screen_h; y++) {
            memcpy(dst + y * fb_pitch_val, src + y * fb_pitch_val, screen_w * 4);
        }
    }
}

int fb_is_double_buffered(void) {
    return use_double_buffer;
}
