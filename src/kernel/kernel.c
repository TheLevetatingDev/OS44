// --- Framebuffer helpers ---

static void *fb;
static uint64_t fb_width, fb_height, fb_pitch;

static inline void put_pixel(uint64_t x, uint64_t y, uint32_t color) {
    if (x >= fb_width || y >= fb_height) return;
    // FIX: Added 'volatile' to strictly forbid Clang from vectorizing the loops into broken SSE operations
    volatile uint32_t *pixel = (volatile uint32_t *)((uint8_t *)fb + y * fb_pitch + x * 4);
    *pixel = color;
}

static void draw_char(char c, uint64_t x, uint64_t y, uint32_t fg, uint32_t bg) {
    if (c < 32 || c > 126) c = '?';
    const uint8_t *glyph = font[c - 32];
    for (int row = 0; row < 8; row++) {
        for (int col = 0; col < 8; col++) {
            uint32_t color = (glyph[row] & (0x80 >> col)) ? fg : bg;
            put_pixel(x + col, y + row, color);
        }
    }
}

static void draw_string(const char *s, uint64_t x, uint64_t y, uint32_t fg, uint32_t bg) {
    while (*s) {
        draw_char(*s++, x, y, fg, bg);
        x += 8;
    }
}

__attribute__((noinline))
static void clear_screen(uint32_t color) {
    for (uint64_t y = 0; y < fb_height; y++)
        for (uint64_t x = 0; x < fb_width; x++)
            put_pixel(x, y, color);
}

// --- Kernel entry ---

void kernel_main(BootInfo *info) {
    // Sanity check the magic number from the bootloader
    if (!info || info->magic != 0xB007B007) {
        // No framebuffer yet, nothing we can do — just halt
        while (1) __asm__("hlt");
    }

    // Set up framebuffer globals
    fb        = info->framebuffer;
    fb_width  = info->fb_width;
    fb_height = info->fb_height;
    fb_pitch  = info->fb_pitch;

    // Clear to black
    clear_screen(COLOR_BLACK);

    // Print Hello, World!
    draw_string("Hello, World!", 32, 32, COLOR_GREEN, COLOR_BLACK);
    draw_string("OS44 kernel is running.", 32, 48, COLOR_WHITE, COLOR_BLACK);

    // Halt forever
    while (1) __asm__("hlt");
}